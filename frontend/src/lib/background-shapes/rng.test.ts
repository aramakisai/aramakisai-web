import { describe, it, expect } from 'vitest';
import { fnv1a, mulberry32 } from './rng';

// 期待値は aramakisai-refine-assets/place.py の Rng クラス (fnv1a→mulberry32) を
// Python で直接呼び出して取得した実測値。日本語 (サロゲート対象外の BMP 文字) を含む
// 文字列で参照実装と数列が一致することを固定する。
describe('fnv1a + mulberry32 (place.py 互換)', () => {
  it.each([
    [
      'アラマキ祭',
      [
        0.12228182679973543, 0.8658446352928877, 0.3619280867278576,
        0.2602052544243634, 0.23737712460570037,
      ],
    ],
    [
      '荒牧祭実行委員会',
      [
        0.029604306677356362, 0.5056430788245052, 0.7519129074644297,
        0.021005780436098576, 0.2264156297314912,
      ],
    ],
    [
      'テスト企画A',
      [
        0.8001255395356566, 0.2864411484915763, 0.0104011797811836,
        0.47581436624750495, 0.2749223436694592,
      ],
    ],
    [
      '模擬店・出店',
      [
        0.18213017284870148, 0.8695171107538044, 0.6531378976069391,
        0.8968050824478269, 0.06055937730707228,
      ],
    ],
    [
      '',
      [
        0.6112444521859288, 0.4935242917854339, 0.7740248835179955,
        0.4122861116193235, 0.8122657814528793,
      ],
    ],
  ] as const)('%s から place.py と同じ乱数列を返す', (seedStr, expected) => {
    const rng = mulberry32(fnv1a(seedStr));
    const actual = [rng(), rng(), rng(), rng(), rng()];
    expect(actual).toEqual(expected);
  });
});
